# A well-formed but impossible value (created: 2026-02-30) raises ValueError, not YAMLError.
YAML_ERRORS = (yaml.YAMLError, ValueError, OverflowError)

HOT_MAX = 75
HOT_NEVER = ("source", "person", "organization")
HOT_ORDER = ["commitment", "event", "goal", "project", "risk", "question", "decision", "idea", "playbook", "topic"]
HEADER = "<!-- Regenerated by system/tools/index.py from the records; never edit by hand. -->\n"


def read_frontmatter(path):
    try:
        with open(path, encoding="utf-8") as f:
            text = f.read()
    except OSError:
        return None
    m = re.match(r"^---\s*\n(.*?)\n---\s*(\n|$)", text, re.S)
    if not m:
        return None
    try:
        fm = yaml.safe_load(m.group(1))
    except YAML_ERRORS:
        return None
    return fm if isinstance(fm, dict) else None


def load_yaml(path):
    try:
        with open(path, encoding="utf-8") as f:
            return yaml.safe_load(f) or {}
    except (OSError,) + YAML_ERRORS:
        return {}


def as_date(value):
    if isinstance(value, datetime.datetime):
        return value.date()
    if isinstance(value, datetime.date):
        return value
    m = re.match(r"^(\d{4})-(\d{2})-(\d{2})", str(value or ""))
    if not m:
        return None
    try:
        return datetime.date(*(int(x) for x in m.groups()))
    except ValueError:
        return None


def clean(value):
    """One line of text, safe inside a ' | '-separated index line."""
    return re.sub(r"\s+", " ", str(value if value is not None else "")).replace("|", "/").strip()


def types(root):
    """{type name: (folder, closed statuses)} for system types and registered user types."""
    schema = load_yaml(os.path.join(root, "system", "schemas", "schema.yaml"))
    closed = schema.get("closed_statuses") or {}
    out = {}
    for name, spec in (schema.get("types") or {}).items():
        if isinstance(spec, dict) and spec.get("folder"):
            out[name] = (str(spec["folder"]), set(closed.get(name) or []))
    reg = load_yaml(os.path.join(root, "user", "extensions", "registry.yaml"))
    for ext in reg.get("extensions") or []:
        if not isinstance(ext, dict) or ext.get("kind") != "type" or not ext.get("path"):
            continue
        fm = read_frontmatter(os.path.join(root, "user", "extensions", str(ext["path"]))) or {}
        # Accept the documented form (folder: user/knowledge/deals/) as well as a bare name (deals),
        # the same way validate.py reads it.
        folder = str(fm.get("folder") or "").strip().strip("/").split("/")[-1]
        if folder and re.match(r"^[a-z][a-z0-9-]*$", folder):
            out.setdefault(str(ext.get("name") or folder), (str(folder), set(fm.get("closed_statuses") or [])))
    return out


def records(root, tmap):
    """Every readable record, as (type, folder, frontmatter)."""
    out = []
    for name, (folder, _) in tmap.items():
        d = os.path.join(root, "user", "knowledge", folder)
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            if not f.endswith(".md"):
                continue
            fm = read_frontmatter(os.path.join(d, f))
            if fm is None:
                continue
            fm.setdefault("id", "%s/%s" % (folder, f[:-3]))
            out.append((name, folder, fm))
    return out


def line(fm):
    aliases = fm.get("aliases") or []
    aliases = [aliases] if isinstance(aliases, str) else aliases
    return "- [[%s]] | %s | aliases: %s | %s | %s | %s" % (
        clean(fm.get("id")), clean(fm.get("title")), clean(", ".join(str(a) for a in aliases)) or "-",
        clean(fm.get("status")), clean(as_date(fm.get("updated")) or fm.get("updated")), clean(fm.get("summary")))


def ref_id(value):
    m = re.search(r"\[\[([a-z]+/[a-z0-9][a-z0-9-]*)\]\]", str(value or ""))
    return m.group(1) if m else None


def hot(recs, tmap, today):
    """The records live right now, in hot.md's group order and keep-order."""
    live = []
    for name, _, fm in recs:
        if name in HOT_NEVER or fm.get("archived") is True or fm.get("superseded_by"):
            continue
        status = fm.get("status")
        if isinstance(status, (list, dict)):    # invalid (validate.py says so); treat as unknown
            status = None
        if status in tmap[name][1]:
            continue
        upd = as_date(fm.get("updated"))
        if name == "commitment":
            due = as_date(fm.get("due"))
            if status == "slipped" or (status in ("open", "slipped") and due and due <= today + datetime.timedelta(14)):
                live.append((name, fm))
        elif name == "event":
            start = as_date(fm.get("start"))
            if status == "scheduled" and start and today <= start <= today + datetime.timedelta(7):
                live.append((name, fm))
        elif name == "goal":
            if status == "active":
                live.append((name, fm))
        elif upd and upd >= today - datetime.timedelta(14):
            live.append((name, fm))

    far = datetime.date.max

    def keep_key(item):
        name, fm = item
        if name == "commitment":
            return (0 if fm.get("status") == "slipped" else 1, as_date(fm.get("due")) or far)
        if name == "event":
            return (2, as_date(fm.get("start")) or far)
        if name == "goal":
            rank = fm.get("rank")
            ranked = isinstance(rank, int) and not isinstance(rank, bool)
            return (3, (0, rank) if ranked else (1, 0))
        return (4, -(as_date(fm.get("updated")) or datetime.date.min).toordinal())

    kept = sorted(live, key=keep_key)
    dropped = 0
    if len(kept) > HOT_MAX:
        dropped = len(kept) - (HOT_MAX - 1)
        kept = kept[:HOT_MAX - 1]
    user_types = sorted(n for n in tmap if n not in HOT_ORDER and n not in HOT_NEVER)
    order = {n: i for i, n in enumerate(HOT_ORDER + user_types)}
    kept.sort(key=lambda item: (order.get(item[0], 99), keep_key(item)))
    out = [line(fm) for _, fm in kept]
    if dropped:
        out.append("- … %d more: see the type indexes" % dropped)
    return out


def build(root, today):
    """{repo-relative path: text} for every index file."""
    tmap = types(root)
    recs = records(root, tmap)
    by_id = {str(fm.get("id")): fm for _, _, fm in recs}
    files = {}
    for name, (folder, _) in sorted(tmap.items(), key=lambda kv: kv[1][0]):
        rows = sorted((fm for n, _, fm in recs if n == name and fm.get("archived") is not True),
                      key=lambda fm: str(fm.get("id")))
        files[folder] = ["# %s" % folder.replace("-", " ").capitalize()] + [line(fm) for fm in rows]
    files["hot"] = ["# Hot: live right now (at most %d lines)" % HOT_MAX] + hot(recs, tmap, today)
    people = []
    for n, _, fm in sorted(recs, key=lambda r: str(r[2].get("id"))):
        if n != "person" or fm.get("archived") is True:
            continue
        org = by_id.get(ref_id(fm.get("org")) or "", {})
        where = clean(org.get("title")) if org else ""
        if fm.get("relationship"):
            where = ("%s (%s)" % (where, clean(fm.get("relationship")))).strip()
        aliases = fm.get("aliases") or []
        aliases = [aliases] if isinstance(aliases, str) else aliases
        people.append("- [[%s]] | %s | %s | %s | %s" % (
            clean(fm.get("id")), clean(fm.get("title")), where or "-", clean(fm.get("role")) or "-",
            clean(", ".join(str(a) for a in aliases)) or "-"))
    files["people-map"] = ["# People map"] + people
    files["archive"] = ["# Archive"] + [line(fm) for _, _, fm in sorted(recs, key=lambda r: str(r[2].get("id")))
                                      if fm.get("archived") is True]
    return {"user/knowledge/_index/%s.md" % k: HEADER + "\n".join(v) + "\n" for k, v in files.items()}


